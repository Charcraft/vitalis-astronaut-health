_ORDEN = sorted(TRAD_EN.items(), key=lambda kv: -len(kv[0]))


def translate(texto: str, idioma: str = "es") -> str:
    if idioma != "en" or not texto:
        return texto
    exacto = TRAD_EN.get(texto)
    if exacto:
        return exacto
    salida = texto
    for es, en in _ORDEN:
        if es in salida:
            salida = salida.replace(es, en)
    return salida
