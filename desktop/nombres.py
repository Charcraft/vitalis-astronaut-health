_LADO = {
    ("l", "m"): "izquierdo", ("r", "m"): "derecho",
    ("l", "f"): "izquierda", ("r", "f"): "derecha",
    ("l", "mp"): "izquierdos", ("r", "mp"): "derechos",
    ("l", "fp"): "izquierdas", ("r", "fp"): "derechas",
}


def nombre_es(clave: str, por_defecto: str = "") -> str:
    """«kidney_l» -> «riñón izquierdo»; «liver» -> «hígado»."""
    if clave in _BASE:
        nombre = _BASE[clave][0]
    elif clave[-2:] in ("_l", "_r") and clave[:-2] in _BASE:
        nombre, genero = _BASE[clave[:-2]]
        nombre = f"{nombre} {_LADO[(clave[-1], genero)]}"
    else:
        return por_defecto or clave.replace("_", " ")
    return nombre[0].upper() + nombre[1:]
